/**
 * Get SEO metadata for a page
 * @param {string} pageKey - page key (home, frozen, pickled, about, etc.)
 * @param {string} language - language code
 * @returns {object} SEO metadata object
 */
export function getSeoMeta(pageKey, language = 'en') {
  const page = seoConfig[pageKey]
  if (!page) return seoConfig.home
  
  const langSuffix = language.charAt(0).toUpperCase() + language.slice(1)
  return {
    title: page[`title${langSuffix}`] || page.titleEn,
    description: page[`description${langSuffix}`] || page.descriptionEn,
    image: page[`image${langSuffix}`] || page.imageEn,
  }
}
